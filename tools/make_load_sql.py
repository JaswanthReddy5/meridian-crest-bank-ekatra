"""Generate sql/01_load_data.sql from the CSV headers in data/.

Every empty CSV field is loaded as NULL (NULLIF(@x, '')), values are
otherwise loaded exactly as sent. Run from the repo root:
    python tools/make_load_sql.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ORDER = [
    "regions", "branches", "products", "officers",
    "customers", "customer_contacts", "legacy_id_map",
    "loan_accounts", "disbursements", "collateral", "emi_schedule",
    "repayments", "nach_mandates",
    "finance_npa_oct2026", "risk_npa_oct2026",
    "cbs_extract_oct2026", "dw_snapshot_oct2026", "load_manifest",
]

out = [
    "-- =====================================================================",
    "-- Meridian Crest Bank · load the 18 delivered CSV files (one per table)",
    "-- Generated by tools/make_load_sql.py — do not edit by hand.",
    "--",
    "-- Paths are relative: run with the mysql client FROM THE REPO ROOT",
    "--   (scripts/run_all.ps1 does this), with local_infile enabled.",
    "-- Empty fields become NULL; every other value is loaded as sent.",
    "-- =====================================================================",
    "",
    "USE meridian_crest_bank;",
    "SET NAMES utf8mb4;",
    "",
]
for t in ORDER:
    with open(ROOT / "data" / f"{t}.csv", newline="", encoding="utf-8") as f:
        cols = next(csv.reader(f))
    vars_ = ", ".join(f"@{c}" for c in cols)
    # Files use CRLF. The Windows mysql client strips the CR, Workbench may
    # not, so split on LF and trim a trailing CR from the last field.
    exprs = [f"NULLIF(@{c}, '')" for c in cols]
    exprs[-1] = f"NULLIF(TRIM(TRAILING '\\r' FROM @{cols[-1]}), '')"
    sets = ",\n    ".join(f"{c} = {e}" for c, e in zip(cols, exprs))
    out += [
        f"-- {t}",
        f"LOAD DATA LOCAL INFILE 'data/{t}.csv'",
        f"INTO TABLE {t}",
        "CHARACTER SET utf8mb4",
        "FIELDS TERMINATED BY ',' OPTIONALLY ENCLOSED BY '\"'",
        "LINES TERMINATED BY '\\n'",
        "IGNORE 1 LINES",
        f"({vars_})",
        f"SET {sets};",
        "",
    ]

out += [
    "-- Row counts after load",
    "SELECT table_name, table_rows_exact FROM (",
    "\n  UNION ALL\n".join(
        f"  SELECT '{t}' AS table_name, COUNT(*) AS table_rows_exact FROM {t}" for t in ORDER
    ),
    ") c;",
    "",
]
(ROOT / "sql" / "01_load_data.sql").write_text("\n".join(out), encoding="utf-8")
print("wrote sql/01_load_data.sql")
